const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const server = fs.readFileSync(path.join(ROOT,'server.js'),'utf8');
const reqMap = {};
for (const m of server.matchAll(/const\s+(\w+)\s*=\s*require\(['"]\.\/routes\/(\w+)['"]\)/g)) reqMap[m[1]] = m[2];
const mountList = [];
for (const m of server.matchAll(/app\.use\(\s*['"](\/api\/[\w-]+)['"]\s*,\s*(\w+)(?:\.(\w+))?\s*\)/g))
  mountList.push({ prefix: m[1], file: reqMap[m[2]] || m[2], sub: m[3] });

// Capture the router VARIABLE each route is defined on (router / capRouter /
// catRouter / …) so multi-router files map to the right mount.
function parseFile(file) {
  let src; try { src = fs.readFileSync(path.join(ROOT,'routes', file + '.js'),'utf8'); } catch { return []; }
  const out = [];
  const re = /(\w*[Rr]outer)\.(get|post|put|delete|patch)\(\s*(['"`])([^'"`]*)\3([^\n]*)/g;
  let m;
  while ((m = re.exec(src))) {
    const rest = m[5], mw = [];
    if (/authenticateToken/.test(rest)) mw.push('auth');
    const rc = rest.match(/requireCapability\(['"]([\w.]+)['"]\)/); if (rc) mw.push('cap:'+rc[1]);
    const ar = rest.match(/authorizeRole\(([^)]*)\)/); if (ar) mw.push('role:'+ar[1].replace(/\s+/g,'').replace(/[\[\]']/g,''));
    const v = rest.match(/validate\(['"](\w+)['"]\)/); if (v) mw.push('val:'+v[1]);
    if (/resolveInstitution/.test(rest)) mw.push('inst');
    const isPub = !/authenticateToken/.test(rest) && !/requireCapability/.test(rest);
    out.push({ varName: m[1], method: m[2].toUpperCase(), rpath: m[4], mw, isPub });
  }
  return out;
}
let total=0,gated=0,validated=0,pub=0,pubWrites=[];
let body='';
for (const mt of mountList.sort((a,b)=>a.prefix.localeCompare(b.prefix))) {
  // A mount with a `.sub` (e.g. orgsRoutes.capRouter) only exposes routes
  // defined on THAT variable; the bare mount exposes the default `router`.
  const targetVar = mt.sub || 'router';
  const routes = parseFile(mt.file).filter(r => r.varName === targetVar); if (!routes.length) continue;
  body += `\n### \`${mt.prefix}\` — routes/${mt.file}.js${mt.sub?' ('+mt.sub+')':''}\n\n`;
  for (const r of routes) {
    total++;
    const full = mt.prefix + (r.rpath==='/'?'':r.rpath);
    if (r.mw.includes('auth')||r.mw.some(x=>x.startsWith('cap:'))) gated++;
    if (r.mw.some(x=>x.startsWith('val:'))) validated++;
    if (r.isPub) { pub++; if (['POST','PUT','DELETE','PATCH'].includes(r.method)) pubWrites.push(`${r.method} ${full}`); }
    const tag = r.isPub ? '🌐 public' : r.mw.join(' · ');
    body += `- \`${r.method} ${full}\` — ${tag}\n`;
  }
}
const header = `# EduOS / JeetMantra — Verified API Inventory

_Auto-generated by backend/scripts/gen-api-inventory.js — parses every router for its path + middleware._

## Totals
- **${total}** endpoints across **${mountList.length}** mounted routers
- **${gated}** auth- or capability-gated
- **${validated}** Joi-validated (write endpoints)
- **${pub}** public (no auth/capability) — ${pubWrites.length} of them are writes (reviewed below)

## Public write endpoints (must be intentional — webhooks / public verify)
${pubWrites.length ? pubWrites.map(x=>'- `'+x+'`').join('\n') : '- (none)'}

## Legend
\`auth\` = authenticateToken · \`cap:x\` = requireCapability('x') · \`role:x\` = authorizeRole([x]) · \`val:x\` = validate('x') · \`inst\` = resolveInstitution · 🌐 = public
`;
fs.writeFileSync(path.join(ROOT,'..','API_INVENTORY_VERIFIED.md'), header + body);
console.log(`${total} endpoints | ${gated} gated | ${validated} validated | ${pub} public (${pubWrites.length} public writes)`);
console.log('PUBLIC WRITES:', pubWrites.join(' | ') || '(none)');
